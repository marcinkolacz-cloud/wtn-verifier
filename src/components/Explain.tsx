import { useState } from 'react';
import { Sparkles } from 'lucide-react';
import { EXPLAIN_URL } from '../lib/ic';
import { Button, Card, CardHeader, ErrorBox, Spinner } from './ui';

type Res = { text: string; model: string; cached: boolean; created: string };

export function Explain({ id }: { id: bigint }) {
  const [lang, setLang] = useState<'pl' | 'en'>();
  const [res, setRes] = useState<Res>();
  const [error, setError] = useState<unknown>();
  const [loading, setLoading] = useState(false);

  if (!EXPLAIN_URL) return null;

  const run = async (l: 'pl' | 'en') => {
    setLang(l);
    setLoading(true);
    setError(undefined);
    setRes(undefined);
    try {
      const r = await fetch(`${EXPLAIN_URL!.replace(/\/$/, '')}/explain?id=${id}&lang=${l}`);
      const j = await r.json();
      if (!r.ok) throw new Error(j.error ?? `HTTP ${r.status}`);
      setRes(j);
    } catch (e) {
      setError(e);
    } finally {
      setLoading(false);
    }
  };

  return (
    <Card>
      <CardHeader
        title={
          <span className="inline-flex items-center gap-2">
            <Sparkles className="size-4 text-accent" /> Explanation
          </span>
        }
        sub="Generated by AI from on-chain action and payload — can be wrong, always check the facts above"
        right={
          <div className="flex gap-1.5">
            {(['pl', 'en'] as const).map((l) => (
              <Button key={l} variant={lang === l ? 'primary' : 'default'} onClick={() => run(l)} disabled={loading}>
                {l.toUpperCase()}
              </Button>
            ))}
          </div>
        }
      />
      {(loading || error || res) && (
        <div className="px-5 py-4">
          {loading && <Spinner label="Generating… (first time ~10 s, then cached)" />}
          {error ? <ErrorBox error={error} onRetry={() => lang && run(lang)} /> : null}
          {res && (
            <>
              <div className="whitespace-pre-wrap text-sm leading-relaxed text-fg/90">{res.text}</div>
              <div className="mt-3 text-[11px] text-muted">
                {res.model.split('/').pop()} · {res.cached ? 'cached' : 'fresh'} · {new Date(res.created).toLocaleString('en-GB')}
              </div>
            </>
          )}
        </div>
      )}
    </Card>
  );
}
